"""Generates ui/renderer/theme.css: the three colour themes (dim, light, contrast).

The renderer's utility classes (bg-slate-900, text-emerald-400 ...) read CSS variables, so a theme is a set of
values for those variables. Neutral (slate) steps are hand-tuned per theme; hue families are derived from the
Tailwind scale as follows:

  dim       Tailwind values with chroma x0.85 (calmer), fills one step darker (600 -> 700) so white text on a
            filled button keeps >= 4.5:1.
  light     the scale is mirrored so "light text on dark" becomes "dark text on light": see LIGHT_STEP.
  contrast  neutrals are pure black/white steps; hue text steps are lighter, fills are darker.

Run:  python scripts/gen_theme.py   (rewrites ui/renderer/theme.css)
Then: npm run test:ts   (ui/tests/contrast_test.ts reads theme.css and checks every text/background pair)
"""
import math
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TW = (ROOT / "node_modules" / "tailwindcss" / "theme.css").read_text(encoding="utf-8")

FAMILIES = ["cyan", "sky", "blue", "indigo", "purple", "pink", "rose", "red", "orange", "amber", "yellow",
            "lime", "green", "emerald", "teal"]
SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950]

SLATE = {
    "dim": {50: "#f7f8fa", 100: "#eceff4", 200: "#dce1e9", 300: "#c6cdd8", 400: "#a9b2c1", 500: "#8c96a8",
            600: "#566073", 700: "#3a4352", 800: "#2a313d", 900: "#1c2129", 950: "#14181e"},
    "light": {50: "#0d1014", 100: "#161a20", 200: "#232831", 300: "#353c48", 400: "#444c5a", 500: "#576071",
              600: "#8d96a6", 700: "#c5cad3", 800: "#dfe2e8", 900: "#fbfbfc", 950: "#f4f5f8"},
    "contrast": {50: "#ffffff", 100: "#ffffff", 200: "#f7f7f7", 300: "#efefef", 400: "#e2e2e2", 500: "#c9c9c9",
                 600: "#a3a3a3", 700: "#6e6e6e", 800: "#5c5c5c", 900: "#0a0a0a", 950: "#000000"},
}
# light theme: which Tailwind step supplies the value for step N (mirror, biased so text steps reach 4.5:1)
LIGHT_STEP = {50: 950, 100: 900, 200: 800, 300: 800, 400: 700, 500: 600, 600: 300, 700: 200, 800: 100, 900: 100, 950: 50}
CONTRAST_STEP = {50: 50, 100: 100, 200: 100, 300: 100, 400: 200, 500: 300, 600: 800, 700: 800, 800: 900, 900: 950, 950: 950}
DIM_STEP = {s: s for s in SHADES}
DIM_STEP[600] = 700


def oklch(family, shade):
    m = re.search(rf"--color-{family}-{shade}:\s*oklch\(([\d.]+)%\s+([\d.]+)\s+([\d.]+)\)", TW)
    assert m, (family, shade)
    return float(m.group(1)) / 100.0, float(m.group(2)), float(m.group(3))


def to_hex(L, C, h):
    a = C * math.cos(math.radians(h))
    b = C * math.sin(math.radians(h))
    l_ = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3
    m_ = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3
    s_ = (L - 0.0894841775 * a - 1.2914855480 * b) ** 3
    rgb = (
        4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_,
        -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_,
        -0.0041960863 * l_ - 0.7034186147 * m_ + 1.7076147010 * s_,
    )
    out = []
    for v in rgb:
        v = max(0.0, min(1.0, v))
        v = 12.92 * v if v <= 0.0031308 else 1.055 * (v ** (1 / 2.4)) - 0.055
        out.append(round(max(0.0, min(1.0, v)) * 255))
    return "#%02x%02x%02x" % tuple(out)


def block(theme, step_map, chroma):
    lines = []
    for s in SHADES:
        lines.append(f"  --c-slate-{s}: {SLATE[theme][s]};")
    for fam in FAMILIES:
        for s in SHADES:
            L, C, h = oklch(fam, step_map[s])
            lines.append(f"  --c-{fam}-{s}: {to_hex(L, C * chroma, h)};")
    return "\n".join(lines)


def main():
    out = [
        "/* GENERATED by scripts/gen_theme.py: edit the script, not this file. */",
        "",
        ":root,\n:root[data-theme='dim'] {",
        "  color-scheme: dark;",
        block("dim", DIM_STEP, 0.85),
        "  --c-white: #f7f8fa;",
        "}",
        "",
        ":root[data-theme='light'] {",
        "  color-scheme: light;",
        block("light", LIGHT_STEP, 1.0),
        "  --c-white: #ffffff;",
        "}",
        "",
        ":root[data-theme='contrast'] {",
        "  color-scheme: dark;",
        block("contrast", CONTRAST_STEP, 1.0),
        "  --c-white: #ffffff;",
        "}",
        "",
        "@theme inline {",
    ]
    for s in SHADES:
        out.append(f"  --color-slate-{s}: var(--c-slate-{s});")
    for fam in FAMILIES:
        for s in SHADES:
            out.append(f"  --color-{fam}-{s}: var(--c-{fam}-{s});")
    out.append("  --color-white: var(--c-white);")
    out.append("}")
    (ROOT / "ui" / "renderer" / "theme.css").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("wrote theme.css")


if __name__ == "__main__":
    main()
