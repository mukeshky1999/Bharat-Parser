"""
Sub-Engine 3.2D: 3-Point Remote Ghost SIM-Binding Trojan Detector.
Detects whether an outbound VMN silent binding SMS was generated by a legitimate local UPI app
or hijacked by an APK SMS-forwarder / banking trojan (e.g., fake RTO e-Challan).
Adheres strictly to AGENTS.md Forensic Invariants and Section 6 of Module 3.2 Spec.
"""

from typing import List, Optional, Set

from src.binding.models import (
    BindingAttributionVerdict,
    NPCICommonLibraryVaultRecord,
)


class GhostSIMBindingTrojanDetector:
    """3-Point correlation engine distinguishing local UPI device binding from trojan ghost-binding."""

    LEGITIMATE_UPI_PACKAGES: Set[str] = {
        "com.phonepe.app",
        "com.google.android.apps.nbu.paisa.user",
        "net.one97.paytm",
        "in.org.npci.upiapp",
        "com.whatsapp",
        "com.dreamplug.androidapp",
        "com.naviapp",
        "money.super.payments",
        "in.amazon.mShop.android.shopping",
        "com.mobikwik_new",
        "com.sbi.lotusintouch",
        "com.sbi.SBIFreedomPlus",
        "com.bankofbaroda.mconnect",
        "com.csam.icici.bank.imobile",
        "com.snapwork.hdfc",
        "com.axis.mobile",
        "com.msf.kbank.mobile",
        "com.myairtelapp",
        "com.freecharge.android",
        "com.bajajfinserv.direct",
        "in.juspay.godel",
        "org.npci.upi.security.pinactivitycomponent",
        "com.canarabank.mobility",
        "com.fss.pnb",
        "com.unionbank.ecommerce.mobile.android",
        "com.infrasofttech.indianbank",
        "com.idfcfirstbank.optimus",
        "com.fedmobile",
        "com.rblbank.mobank",
        "com.finopaytech.bpay",
        "in.ippbonline.mobile",
    }

    SUSPICIOUS_NAME_KEYWORDS = (
        ".apk",
        "challan",
        "parivahan",
        "pmkisan",
        "bijli",
        "electricity",
        "update",
        "trojan",
        "spy",
        "forwarder",
        "shell",
        "dropper",
        "mule",
    )

    def is_legitimate_upi_package(self, package_name: Optional[str]) -> bool:
        """Determines if a package name matches an authorized Indian UPI or banking application."""
        if not package_name:
            return False
        pkg = package_name.strip().lower()
        if pkg in self.LEGITIMATE_UPI_PACKAGES:
            return True
        for legit in self.LEGITIMATE_UPI_PACKAGES:
            if legit in pkg:
                return True
        return False

    def is_trojan_or_sideloaded_package(self, package_name: Optional[str]) -> bool:
        """Detects whether a package name exhibits markers of sideloaded trojans or malicious APKs."""
        if not package_name:
            return False
        pkg = package_name.strip().lower()
        if any(keyword in pkg for keyword in self.SUSPICIOUS_NAME_KEYWORDS):
            return True
        return False

    def classify_binding_sms(
        self,
        creator_package: Optional[str],
        sms_timestamp_ms: Optional[int] = None,
        cl_records: Optional[List[NPCICommonLibraryVaultRecord]] = None,
        is_sideloaded: bool = False,
    ) -> str:
        """
        Executes the 3-Point Correlation Test:
        Point 1: Originating Package Lineage (Official UPI vs Sideloaded APK).
        Point 2: Matching Local Common Library (CL) Key Token Registration.
        Point 3: Final Attribution Verdict Assignment.
        """
        if not creator_package:
            return BindingAttributionVerdict.UNVERIFIED_OR_FAILED_BINDING.value

        pkg = creator_package.strip().lower()

        # Check Point 1: Sideloaded trojan / malicious APK markers
        if is_sideloaded or self.is_trojan_or_sideloaded_package(pkg):
            return BindingAttributionVerdict.COMPROMISED_REMOTE_GHOST_SIM_BINDING_VIA_TROJAN.value

        # Check Point 1: Official verified UPI package
        if self.is_legitimate_upi_package(pkg):
            return BindingAttributionVerdict.VERIFIED_LOCAL_HANDSET_AND_SIM_BINDING.value

        # Check Point 2: Unknown package without local CL registration
        has_local_cl_match = False
        if cl_records:
            for rec in cl_records:
                if rec.cl_k0_token_present == 1:
                    has_local_cl_match = True
                    break

        if not has_local_cl_match:
            return BindingAttributionVerdict.COMPROMISED_REMOTE_GHOST_SIM_BINDING_VIA_TROJAN.value

        return BindingAttributionVerdict.UNVERIFIED_OR_FAILED_BINDING.value
